export const formatVND = (amount: number): string => {
  return new Intl.NumberFormat('vi-VN', { style: 'currency', currency: 'VND' }).format(Math.round(amount || 0));
};

export const numberToVietnameseWords = (amount: number): string => {
  if (!amount || amount === 0) return 'Không đồng';
  const units = ['', 'nghìn', 'triệu', 'tỷ'];
  const digits = ['không', 'một', 'hai', 'ba', 'bốn', 'năm', 'sáu', 'bảy', 'tám', 'chín'];

  const readThreeDigits = (n: number, showZeroHundred: boolean): string => {
    let res = '';
    const h = Math.floor(n / 100);
    const t = Math.floor((n % 100) / 10);
    const u = n % 10;

    if (h > 0 || showZeroHundred) {
      res += digits[h] + ' trăm ';
    }
    if (t > 1) {
      res += digits[t] + ' mươi ';
      if (u === 1) res += 'mốt ';
      else if (u === 5) res += 'lăm ';
      else if (u > 0) res += digits[u] + ' ';
    } else if (t === 1) {
      res += 'mười ';
      if (u === 5) res += 'lăm ';
      else if (u > 0) res += digits[u] + ' ';
    } else {
      if ((h > 0 || showZeroHundred) && u > 0) {
        res += 'lẻ ' + digits[u] + ' ';
      } else if (u > 0) {
        res += digits[u] + ' ';
      }
    }
    return res.trim();
  };

  let num = Math.round(amount);
  let groups: number[] = [];
  while (num > 0) {
    groups.push(num % 1000);
    num = Math.floor(num / 1000);
  }

  let words = '';
  for (let i = groups.length - 1; i >= 0; i--) {
    const g = groups[i];
    if (g > 0) {
      const gStr = readThreeDigits(g, i < groups.length - 1);
      words += gStr + ' ' + units[i] + ' ';
    }
  }

  words = words.trim() + ' đồng chẵn.';
  return words.charAt(0).toUpperCase() + words.slice(1);
};
