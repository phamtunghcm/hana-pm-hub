// Tạo ma trận chấm công mẫu cho tháng 10/2026 (1 -> 31)
export function getInitialAttendanceMatrix(): AttendanceMatrixRecord[] {
  return INITIAL_EMPLOYEES.map(emp => {
    const chamCong: Record<number, 'V' | '1/2' | 'P' | 'O' | 'KL' | 'M' | 'OFF'> = {};
    let congThucTe = 0;
    let nghiPhep = 0;
    let khongLuong = 0;
    let diMuon = 0;

    for (let day = 1; day <= 31; day++) {
      // Chủ nhật là ngày nghỉ tuần
      // Tháng 10/2026: ngày 4, 11, 18, 25 là Chủ nhật
      if ([4, 11, 18, 25].includes(day)) {
        chamCong[day] = 'OFF';
      } else if (day > 6) {
        // Những ngày chưa tới (hôm nay là ngày 6)
        // Để trạng thái chấm công mặc định
        chamCong[day] = 'V';
        congThucTe += 1;
      } else {
        // Các ngày đã qua 1 - 6
        if (emp.maNV === 'NV002' && day === 3) {
          chamCong[day] = 'M';
          diMuon += 1;
          congThucTe += 1;
        } else if (emp.maNV === 'NV003' && day === 5) {
          chamCong[day] = '1/2';
          congThucTe += 0.5;
        } else {
          chamCong[day] = 'V';
          congThucTe += 1;
        }
      }
    }

    return {
      maNV: emp.maNV,
      hoTen: emp.hoTen,
      chucVuLabel: emp.chucVuLabel,
      chiNhanhTen: emp.chiNhanhTen,
      chamCongTheoNgay: chamCong,
      ngayCongChuan: 26,
      ngayCongThucTe: Math.min(26, congThucTe),
      ngayNghiPhep: nghiPhep,
      ngayNghiKhongLuong: khongLuong,
      soLanDiMuon: diMuon,
    };
  });
}
